export const getTrendingProducts = (tag = "all") => {
  if (tag === "all") return PRODUCTS.slice(0, 8);
  return PRODUCTS.filter((p) => p.tags.includes(tag)).slice(0, 8);
};
export const getNewArrivals = () => PRODUCTS.filter((p) => p.isNew || p.tags.includes("new"));
